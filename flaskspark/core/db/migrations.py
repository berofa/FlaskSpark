"""Migrations per module (Alembic, without Flask-Migrate): every module keeps its own history, FlaskSpark runs them.

- A module ships its migrations in <package>/migrations/versions/: its own branch of the database's history
  (branch_labels = (<module name>,), the first revision with down_revision = None), independent of the others. A
  revision may name another module's revision in depends_on (e.g. a foreign key to its table): Alembic applies that
  one first and then keeps only the dependent revision in alembic_version; positions() still finds where every
  history stands (the dependency is «contained» in the dependent revision).
- The core has its own branch "core" (flaskspark/core/db/versions: core_settings, core_role_area, core_user_settings,
  core_user_role) and, with sign-in, "signin" (versions_signin: FlaskSpark's users and roles).
- upgrade(): every loaded module's branch (and the core's) to its head; the web service and the supervisor run it at
  their start, with a backup of the database first when there is something to do (flaskspark.core.backup).
- revision(): a new revision of one module, autogenerated against that module's tables only (manifest TABLES and the
  tables of its MODELS).
- A module the application no longer delivers (removed or renamed in a new version) leaves its revision in
  alembic_version. That is no error: the start warns, the status tile «Modules» names it, and the histories of the
  delivered modules are upgraded as usual; Alembic only ever sees the revisions it knows (run_env), the others' rows
  stay untouched, and so do the module's tables and data. The table core_module_chains (record(), at every upgrade)
  remembers per module its revision and its tables, so the module is named later; when it comes back, its history
  goes on from where it stood. A revision that belongs to no module ever recorded (e.g. a database of another
  application) is treated the same, with a warning of its own. «Settings › Data» and `<app> data` clean up what such a
  module left behind (flaskspark.core.leftovers).
- adopt(): a database whose tables come from an earlier, single history (e.g. Flask-Migrate in web/migrations): the
  revisions it holds that no history knows are dropped, and every history whose tables all exist is stamped at its
  first revision (which describes the tables as they were when the module got its own history); upgrade() then
  applies what came after. differences() shows what still differs between the models and the database.

    <app> db upgrade | current | check | adopt
    <app> db revision -m "add a column" --module notes

The classic layout (one history in web/migrations, Flask-Migrate) keeps working: metadata() for its env.py and
missing(); classic() tells it apart (FlaskSpark runs nothing itself there).
"""

from __future__ import annotations

import logging
import os
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path

log = logging.getLogger(__name__)

HERE = Path(__file__).resolve().parent
ALEMBIC_DIR = HERE / "alembic"  # env.py and the template of new revisions
CORE_VERSIONS = HERE / "versions"
SIGNIN_VERSIONS = HERE / "versions_signin"
VERSION_TABLE = "alembic_version"
SIGNIN_TABLES = frozenset({"roles", "user"})
CORE_FIRST_TABLES = frozenset({"core_settings", "core_role_area", "core_user_settings", "core_user_role"})
RECORD_TABLE = "core_module_chains"


class MigrationError(RuntimeError):
    """The database cannot be migrated as it is (e.g. revisions of an earlier history: `<app> db adopt`)."""


@dataclass(frozen=True)
class Chain:
    """The history of one module (or of the core): its branch label, its versions directory and its tables."""

    name: str
    versions: Path
    tables: frozenset = frozenset()
    models: tuple = ()
    target: bool = True  # upgrade() brings it to its head (False: only known, e.g. a module that is not loaded)
    first: frozenset = frozenset()  # the tables of its first revision when they differ from `tables` (adopt())


@dataclass
class State:
    """Where the database stands: per history its revision (None: none yet) and its head."""

    current: dict = field(default_factory=dict)  # history -> revision or None
    heads: dict = field(default_factory=dict)  # history -> head revision
    unknown: list = field(default_factory=list)  # revisions in the database no history knows
    unversioned: dict = field(default_factory=dict)  # history -> its tables that exist without a revision
    vanished: dict = field(default_factory=dict)  # module no longer delivered -> {revisions, tables, label}
    foreign: list = field(default_factory=list)  # unknown revisions of no module ever recorded

    @property
    def pending(self) -> list[str]:
        return [b for b, head in self.heads.items() if self.current.get(b) != head]


# --- the classic layout -------------------------------------------------------------------------------------------
def classic() -> bool:
    """The project keeps one history of its own in web/migrations (Flask-Migrate)."""
    from .. import paths

    return (paths.WEB_DIR / "migrations").is_dir()


def metadata(target_db=None) -> list:
    """The classic layout's web/migrations/env.py: the metadata for Alembic's autogenerate, FlaskSpark's
    (Flask-SQLAlchemy of the current app, or `target_db`) and the database API's with every table of the modules."""
    from . import load_models

    api = load_models()
    if target_db is None:
        from flask import current_app, has_app_context

        if not has_app_context() or "migrate" not in current_app.extensions:
            return [api]
        target_db = current_app.extensions["migrate"].db
    flask = target_db.metadatas[None] if hasattr(target_db, "metadatas") else target_db.metadata
    return [flask, api]


def missing(url: str | None = None) -> list[str]:
    """The tables of the database API (core and modules) the database does not have yet."""
    from .. import config, modules
    from . import has_table, load_models, session, for_module, CORE

    cfg = config.load()
    load_models(cfg)
    names = sorted({t for m in modules.load(cfg) for t in _tables_of(m)})
    with session(for_module(CORE, url) if url else None) as s:
        return [name for name in names if not has_table(s, name)]


# --- the histories ------------------------------------------------------------------------------------------------
def signin(cfg) -> bool:
    """The access of this installation signs users in (FlaskSpark's users and roles are needed)."""
    from ..web.access import access_class

    return access_class((cfg.get("auth") if cfg is not None else None) or "none").LOGIN_PROVIDER is not None


def _tables_of(manifest) -> frozenset:
    """A module's own tables: its TABLES and the tables of the classes its MODELS define."""
    from . import Model

    models = set(manifest.MODELS)
    found = set(manifest.TABLES)
    for mapper in Model.registry.mappers:
        if mapper.class_.__module__ in models:
            found |= {t.name for t in mapper.tables}
    return frozenset(found)


def chains(cfg) -> list[Chain]:
    """Every history this installation knows: the core's, sign-in's, and those of the modules that ship one (also of a
    delivered module that is not loaded, for a missing dependency or left out by config.yaml `modules:`: its revisions
    stay known, it is only not upgraded)."""
    import importlib

    from .. import discovery, modules
    from ..core_module import Core
    from . import load_models

    load_models(cfg)
    out = [Chain("core", CORE_VERSIONS, frozenset(Core.TABLES), Core.MODELS, first=CORE_FIRST_TABLES),
           Chain("signin", SIGNIN_VERSIONS, SIGNIN_TABLES, (), target=signin(cfg))]
    loaded = {m.NAME: m for m in modules.load(cfg)[1:]}
    for manifest in modules.selected_manifests(cfg):
        name, package = manifest.NAME, manifest.PACKAGE
        if name not in loaded:
            for models in manifest.MODELS:
                importlib.import_module(models)
        directory = discovery.package_dir(package)
        versions = directory / "migrations" / "versions" if directory is not None else None
        if versions is None or not versions.is_dir():
            if manifest.MODELS:
                log.debug("module %r has tables but no migrations (%s)", name, versions)
            continue
        out.append(Chain(name, versions, _tables_of(manifest), tuple(manifest.MODELS), target=name in loaded))
    # installed, but left out by config.yaml `modules:`: only its revisions known (nothing of it is imported)
    have = {c.name for c in out}
    for name, package in modules.installed().items():
        directory = discovery.package_dir(package) if name not in have else None
        versions = directory / "migrations" / "versions" if directory is not None else None
        if versions is not None and versions.is_dir():
            out.append(Chain(name, versions, target=False))
    return out


def chain(cfg, name: str) -> Chain:
    """The history of a loaded module, also before it has a revision (its versions directory may not exist yet)."""
    found = next((c for c in chains(cfg) if c.name == name), None)
    if found is not None:
        return found
    from .. import modules

    manifest = modules.get(cfg, name)
    if manifest is None or name == "core":
        raise MigrationError(f"no module {name!r} is loaded")
    directory = modules.directory(manifest)
    return Chain(name, directory / "migrations" / "versions", _tables_of(manifest), tuple(manifest.MODELS))


def _url(url: str | None) -> str:
    from . import default_url

    return url or default_url()


def alembic_config(cfg, url: str | None = None, histories: list[Chain] | None = None):
    """Alembic's configuration: FlaskSpark's env.py, every history's versions directory, the database."""
    from alembic.config import Config

    histories = chains(cfg) if histories is None else histories
    config = Config()
    config.set_main_option("script_location", str(ALEMBIC_DIR))
    config.set_main_option("path_separator", "os")
    config.set_main_option("version_locations", os.pathsep.join(str(c.versions) for c in histories
                                                                 if c.versions.is_dir()))
    config.attributes["flaskspark_url"] = _url(url)
    return config


def script(cfg, histories: list[Chain] | None = None):
    from alembic.script import ScriptDirectory

    return ScriptDirectory.from_config(alembic_config(cfg, histories=histories))


def _branch_head(scripts, name: str) -> str | None:
    try:
        rev = scripts.get_revision(f"{name}@head")
    except Exception:  # noqa: BLE001 - no such branch (no revisions yet)
        return None
    return rev.revision if rev is not None else None


def _branch_base(scripts, name: str) -> str | None:
    for base in scripts.get_bases():
        if name in (scripts.get_revision(base).branch_labels or ()):
            return base
    return None


def _branch_of(scripts, revision: str) -> str | None:
    """The history a revision belongs to (the label of its branch); None if no history knows it."""
    try:
        rev = scripts.get_revision(revision)
    except Exception:  # noqa: BLE001 - unknown revision
        return None
    while rev is not None:
        if rev.branch_labels:
            return next(iter(rev.branch_labels))
        down = rev.down_revision
        if down is None:
            return None
        rev = scripts.get_revision(down if isinstance(down, str) else down[0])
    return None


def _downs(rev, dependencies: bool = True) -> tuple:
    """The revisions directly below `rev`: its down revisions and (dependencies) those it depends_on."""
    if dependencies and hasattr(rev, "_all_down_revisions"):
        return tuple(rev._all_down_revisions)
    down = rev.down_revision
    out = () if down is None else ((down,) if isinstance(down, str) else tuple(down))
    if dependencies:
        out += tuple(getattr(rev, "_resolved_dependencies", ()) or ())
    return out


def positions(scripts, rows) -> tuple[dict[str, str], list[str]]:
    """Where every history stands, from the rows of alembic_version: ({history: revision}, [rows no history knows]).

    A revision that depends_on a revision of another history (e.g. a foreign key to its table) «contains» it: Alembic
    keeps only the dependent one in alembic_version and removes the other history's row when it would be its head. So
    a history stands at the latest of its revisions among the rows and everything they need (down revisions and
    dependencies, transitively), not only at a row of its own."""
    known: dict[str, set] = {}
    unknown = []
    seen: set = set()
    for row in rows:
        if _branch_of(scripts, row) is None:
            unknown.append(row)
            continue
        todo = [row]
        while todo:
            name = todo.pop()
            if name in seen:
                continue
            seen.add(name)
            rev = scripts.get_revision(name)
            if rev is None:
                continue
            branch = _branch_of(scripts, rev.revision)
            if branch is not None:
                known.setdefault(branch, set()).add(rev.revision)
            todo.extend(_downs(rev))
    out = {}
    for branch, revisions in known.items():
        below = {d for r in revisions for d in _downs(scripts.get_revision(r), dependencies=False)}
        tips = [r for r in revisions if r not in below]
        out[branch] = next((r for r in rows if r in tips), tips[0] if tips else None)
    return out, unknown


def _version_rows(connection) -> list[str]:
    from sqlalchemy import inspect as sa_inspect, text

    if not sa_inspect(connection).has_table(VERSION_TABLE):
        return []
    return [r[0] for r in connection.execute(text(f"SELECT version_num FROM {VERSION_TABLE}"))]


def _record_rows(connection) -> dict[str, dict]:
    """The modules recorded at earlier starts (core_module_chains): name -> {label, revision, tables, version, seen};
    {} without the table (before the core's migration)."""
    from sqlalchemy import inspect as sa_inspect, select

    from ..models import ModuleChain

    if not sa_inspect(connection).has_table(RECORD_TABLE):
        return {}
    table = ModuleChain.__table__
    return {r.name: {"label": r.label, "revision": r.revision, "tables": list(r.tables or []), "version": r.version,
                     "seen": r.seen} for r in connection.execute(select(table))}


def state(cfg, url: str | None = None) -> State:
    """Where the database stands (nothing is changed)."""
    from sqlalchemy import inspect as sa_inspect

    from . import engine

    from .. import modules

    histories = chains(cfg)
    scripts = script(cfg, histories)
    out = State()
    with engine(_url(url)).connect() as connection:
        rows = _version_rows(connection)
        existing = set(sa_inspect(connection).get_table_names())
        recorded = _record_rows(connection)
    names = {c.name for c in histories} | modules.delivered_names(cfg)
    by_revision = {r["revision"]: name for name, r in recorded.items() if r["revision"] and name not in names}
    known, unknown = positions(scripts, rows)
    for rev in unknown:
        out.unknown.append(rev)
        module = by_revision.get(rev)
        if module is None:
            out.foreign.append(rev)
        else:
            entry = out.vanished.setdefault(module, {"revisions": [], "label": recorded[module]["label"],
                                                     "tables": sorted(set(recorded[module]["tables"]) & existing)})
            entry["revisions"].append(rev)
    for c in histories:
        if not c.target:
            continue
        head = _branch_head(scripts, c.name)
        if head is None:
            continue
        out.heads[c.name] = head
        out.current[c.name] = known.get(c.name)
        if known.get(c.name) is None and c.tables & existing:
            out.unversioned[c.name] = sorted(c.tables & existing)
    return out


current = state


def _refusal(found: State) -> str | None:
    """Why the database cannot be migrated: tables of a delivered history without its revision (an earlier single
    history: `db adopt`). Revisions no history knows alone are no reason (a module no longer delivered, warnings())."""
    if found.unversioned:
        tables = "; ".join(f"{b}: {', '.join(t)}" for b, t in found.unversioned.items())
        earlier = (f"; the database holds revisions no installed history knows ({', '.join(found.foreign)})"
                   if found.foreign else "")
        return f"tables exist without a revision of their history ({tables}){earlier}: run `db adopt`"
    return None


def warnings(found: State) -> list[str]:
    """What the start warns of: modules no longer delivered (their revision and tables are kept), revisions of no
    known module."""
    out = []
    for name, entry in found.vanished.items():
        tables = ", ".join(entry["tables"]) or "none left"
        out.append(f"module {name!r} is no longer delivered: its revision {', '.join(entry['revisions'])} stays in "
                   f"{VERSION_TABLE} and its tables are kept ({tables}); «Settings › Data» or `data` list what it left")
    for rev in found.foreign:
        out.append(f"revision {rev} in {VERSION_TABLE} belongs to no module this application delivers or delivered "
                   "(e.g. a database of another application): left as it is, the delivered histories are migrated")
    return out


@contextmanager
def _lock():
    """One process migrates at a time (the web service and the supervisor may start together)."""
    from .. import paths

    path = paths.STATE_DIR / "migrations.lock"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as handle:
        try:
            import fcntl
        except ImportError:  # pragma: no cover - not POSIX
            yield
            return
        fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def _backup(cfg, url: str) -> str | None:
    """A copy of the database before it is changed (none of a database without tables)."""
    from sqlalchemy import inspect as sa_inspect

    from .. import backup
    from . import engine

    with engine(url).connect() as connection:
        if not sa_inspect(connection).get_table_names():
            return None
    dest = backup.settings(cfg)["dir"]
    dest.mkdir(parents=True, exist_ok=True)
    try:
        return str(backup.backup_db(dest, backup.stamp(), url))
    except FileNotFoundError:
        return None


def upgrade(cfg, url: str | None = None, backup_first: bool = True) -> dict:
    """Bring every loaded history to its head and record the delivered modules (record()). Returns {"applied":
    {history: [from, to]}, "backup": path or None, "warnings": [...]}. Revisions no history knows (a module no longer
    delivered) are left alone and only warned of. Refuses (MigrationError) tables without a revision of their history
    (an earlier single history: `db adopt`)."""
    from alembic import command

    url = _url(url)
    with _lock():
        found = state(cfg, url)
        refusal = _refusal(found)
        if refusal:
            raise MigrationError(refusal)
        notes = warnings(found)
        for note in notes:
            log.warning("database: %s", note)
        pending = found.pending
        result = {"applied": {}, "backup": None, "warnings": notes}
        if pending:
            result["backup"] = _backup(cfg, url) if backup_first else None
            config = alembic_config(cfg, url)
            for branch in pending:
                log.info("migrate %s: %s -> %s", branch, found.current.get(branch) or "empty", found.heads[branch])
                command.upgrade(config, f"{branch}@head")
            result["applied"] = {b: [found.current.get(b), found.heads[b]] for b in pending}
        record(cfg, url)
        return result


def record(cfg, url: str | None = None) -> None:
    """Note every selected module (loaded, or not for a missing dependency) in core_module_chains: its history's
    revision in the database, its tables, its label, the version that delivered it, now. Rows of the others stay as
    they were (a module left out by config.yaml `modules:` as last seen, one no longer delivered too)."""
    import time

    from .. import modules
    from ..models import ModuleChain
    from . import CORE, engine, for_module, session

    url = _url(url)
    histories = {c.name: c for c in chains(cfg)}
    scripts = script(cfg, list(histories.values()))
    with engine(url).connect() as connection:
        rows = _version_rows(connection)
    current, _unknown = positions(scripts, rows)
    now = time.time()
    with session(for_module(CORE, url)) as s:
        for manifest in modules.selected_manifests(cfg):
            c = histories.get(manifest.NAME)
            tables = sorted(c.tables if c is not None else _tables_of(manifest))
            row = s.get(ModuleChain, manifest.NAME)
            if row is None:
                row = ModuleChain(name=manifest.NAME)
                s.add(row)
            row.label, row.revision, row.tables = str(manifest.LABEL or ""), current.get(manifest.NAME), tables
            row.version, row.seen = modules.version(manifest), now


def recorded(url: str | None = None) -> dict[str, dict]:
    """The modules recorded in core_module_chains: name -> {label, revision, tables, version, seen}."""
    from . import engine

    with engine(_url(url)).connect() as connection:
        return _record_rows(connection)


def forget(cfg, names: list[str] = (), revisions: list[str] = (), url: str | None = None) -> None:
    """Remove the record of modules (core_module_chains) and revisions from alembic_version (cleaning up after a
    module no longer delivered: a module that comes back starts its history from the beginning). Only modules that
    are not delivered and revisions no history knows."""
    from sqlalchemy import Column, MetaData, String, Table, delete, inspect as sa_inspect

    from ..models import ModuleChain
    from . import engine

    from .. import modules

    url = _url(url)
    histories = chains(cfg)
    known = {c.name for c in histories} | modules.delivered_names(cfg)
    names = [n for n in names if n not in known and n != "core"]
    scripts = script(cfg, histories)
    revisions = [r for r in revisions if _branch_of(scripts, r) is None]
    with engine(url).begin() as connection:
        if names and sa_inspect(connection).has_table(RECORD_TABLE):
            connection.execute(delete(ModuleChain.__table__).where(ModuleChain.__table__.c.name.in_(names)))
        if revisions and sa_inspect(connection).has_table(VERSION_TABLE):
            table = Table(VERSION_TABLE, MetaData(), Column("version_num", String(32)))
            connection.execute(delete(table).where(table.c.version_num.in_(revisions)))


def upgrade_on_start(cfg=None) -> None:
    """At the start of the web service or the supervisor: upgrade(), logged; nothing in the classic layout. A database
    that needs `db adopt` stops the start (SystemExit with the reason)."""
    if classic():
        return
    from .. import config as _config

    cfg = cfg or _config.load()
    try:
        result = upgrade(cfg)
    except MigrationError as exc:
        raise SystemExit(f"Database not migrated: {exc}") from None
    if result["applied"]:
        log.warning("database migrated: %s (backup: %s)", ", ".join(result["applied"]), result["backup"] or "none")


def revision(cfg, module: str, message: str, autogenerate: bool = True, url: str | None = None) -> list[Path]:
    """A new revision of `module` in its versions directory (created if needed), autogenerated against its tables
    only (the database must be at the heads: MigrationError «run db upgrade first» otherwise). Returns the new files
    (none if autogenerate found no change)."""
    from alembic import command

    from alembic.util.exc import CommandError

    target = chain(cfg, module)
    if autogenerate:  # Alembic compares with the database: it must be at every head (else a traceback of Alembic's)
        found = state(cfg, url)
        behind = _refusal(found) or (found.pending and f"{', '.join(found.pending)} not at the head")
        if behind:
            raise MigrationError(f"the database is not up to date ({behind}): run `{cfg.app_name} db upgrade` first")
    # Alembic's autogenerate wants the database at every head it knows: only the histories that are upgraded here
    histories = [c for c in chains(cfg) if c.target]
    if all(c.name != module for c in histories):
        histories.append(target)
    target.versions.mkdir(parents=True, exist_ok=True)
    config = alembic_config(cfg, url, histories)
    config.attributes["flaskspark_autogenerate"] = target
    head = _branch_head(script(cfg, histories), module)
    before = set(target.versions.glob("*.py"))
    try:
        command.revision(config, message=message, autogenerate=autogenerate, head=f"{module}@head" if head else "base",
                         branch_label=None if head else module, version_path=str(target.versions))
    except CommandError as exc:
        raise MigrationError(f"{exc} (run `{cfg.app_name} db upgrade` first if the database is behind)") from exc
    return sorted(set(target.versions.glob("*.py")) - before)


def filters(target: Chain | None) -> dict:
    """Alembic's include_name for one history's tables (None: every table)."""
    if target is None:
        return {}
    tables = target.tables

    def include_name(name, type_, _parent):
        return name in tables if type_ == "table" else True

    def include_object(obj, name, type_, _reflected, _compare_to):
        return name in tables if type_ == "table" else True

    return {"include_name": include_name, "include_object": include_object}


def differences(cfg, url: str | None = None) -> dict[str, list]:
    """What differs between the models of every loaded history and the database: history -> differences (Alembic's
    autogenerate, the tables of that history only). Sign-in's tables (Flask-SQLAlchemy) are not compared."""
    from alembic.autogenerate import compare_metadata
    from alembic.migration import MigrationContext

    from . import Model, engine

    out = {}
    with engine(_url(url)).connect() as connection:
        for c in chains(cfg):
            if not c.target or c.name == "signin":
                continue
            context = MigrationContext.configure(connection, opts={"compare_type": True, **filters(c)})
            diffs = compare_metadata(context, Model.metadata)
            flat = [d for diff in diffs for d in (diff if isinstance(diff, list) else [diff])]
            if flat:
                out[c.name] = flat
    return out


def adopt(cfg, url: str | None = None) -> dict:
    """Take over a database whose tables come from an earlier history: drop the revisions no history knows (but those
    of a module recorded before and no longer delivered: they stay for its return), stamp
    every history whose tables all exist (and that has no revision yet) at its first revision. A history with only some
    of its tables refuses (MigrationError, nothing changed). Returns what was done (upgrade() afterwards applies the
    revisions after the first ones and creates the histories that were "new")."""
    from sqlalchemy import Column, MetaData, PrimaryKeyConstraint, String, Table, delete, insert, inspect as sa_inspect

    from .. import modules
    from . import engine

    url = _url(url)
    histories = chains(cfg)
    scripts = script(cfg, histories)
    report = {"dropped": [], "stamped": {}, "kept": {}, "new": [], "backup": None}
    with _lock():
        report["backup"] = _backup(cfg, url)
        with engine(url).begin() as connection:
            existing = set(sa_inspect(connection).get_table_names())
            names = {c.name for c in histories} | modules.delivered_names(cfg)
            vanished = {r["revision"] for n, r in _record_rows(connection).items() if r["revision"] and n not in names}
            rows = _version_rows(connection)
            known, unknown = positions(scripts, rows)
            for rev in unknown:
                if rev in vanished:
                    report["kept"].setdefault("no longer delivered", []).append(rev)
                else:
                    report["dropped"].append(rev)
            table = Table(VERSION_TABLE, MetaData(), Column("version_num", String(32), nullable=False),
                          PrimaryKeyConstraint("version_num", name=f"{VERSION_TABLE}_pkc"))
            table.create(connection, checkfirst=True)
            if report["dropped"]:
                connection.execute(delete(table).where(table.c.version_num.in_(report["dropped"])))
            problems = []
            for c in histories:
                base = _branch_base(scripts, c.name)
                if base is None:
                    continue
                if c.name in known:
                    report["kept"][c.name] = known[c.name]
                    continue
                first = c.first or c.tables
                present = first & existing
                if not present:
                    if c.target:
                        report["new"].append(c.name)
                elif present == first:
                    connection.execute(insert(table).values(version_num=base))
                    report["stamped"][c.name] = base
                else:
                    problems.append(f"{c.name}: only {', '.join(sorted(present))} of {', '.join(sorted(first))}")
            if problems:
                raise MigrationError("tables of a history are missing, nothing was changed: " + "; ".join(problems))
    return report


def _migration_engine(url: str):
    """An engine of its own for the migrations: SQLite without foreign key enforcement (batch operations copy and
    drop tables; the foreign keys are checked after the run)."""
    from sqlalchemy import create_engine, event
    from sqlalchemy.pool import NullPool

    from .databases import database_for

    database = database_for(url)
    database.prepare(url)
    eng = create_engine(url, poolclass=NullPool)
    database.configure(eng)
    if database.scheme == "sqlite":
        def _no_foreign_keys(dbapi_connection, _record):
            cursor = dbapi_connection.cursor()
            cursor.execute("PRAGMA foreign_keys=OFF")
            cursor.close()

        event.listen(eng, "connect", _no_foreign_keys)
    return eng


def _known_heads_only(migration_context, scripts) -> None:
    """Alembic sees only the revisions of alembic_version its histories know: a module no longer delivered leaves its
    row there, which Alembic could not resolve. Its row stays untouched (Alembic updates rows by their revision)."""
    read = migration_context.get_current_heads

    def known_heads():
        out = []
        for rev in read():
            try:
                if scripts.get_revision(rev) is not None:
                    out.append(rev)
            except Exception:  # noqa: BLE001 - a revision no history knows
                continue
        return tuple(out)

    migration_context.get_current_heads = known_heads


def run_env(context) -> None:
    """flaskspark/core/db/alembic/env.py: the migrations; autogenerate compares only the tables of the history a new
    revision belongs to, and writes no revision without a change."""
    from . import load_models

    config = context.config
    if context.is_offline_mode():
        raise MigrationError("offline migrations (SQL scripts) are not supported")
    target = config.attributes.get("flaskspark_autogenerate")
    metadata = load_models()

    def skip_empty(_context, _revision, directives):
        if target is not None and directives and directives[0].upgrade_ops.is_empty():
            log.warning("no changes of %s's tables: no revision written", target.name)
            directives[:] = []

    url = config.attributes["flaskspark_url"]
    eng = _migration_engine(url)
    try:
        with eng.connect() as connection:
            context.configure(connection=connection, target_metadata=metadata, render_as_batch=True,
                              compare_type=True, version_table=VERSION_TABLE, process_revision_directives=skip_empty,
                              **filters(target))
            _known_heads_only(context.get_context(), context.script)
            with context.begin_transaction():
                context.run_migrations()
            connection.commit()
            if eng.dialect.name == "sqlite":
                broken = connection.exec_driver_sql("PRAGMA foreign_key_check").fetchall()
                if broken:
                    log.error("foreign keys broken after the migration: %s", broken[:10])
    finally:
        eng.dispose()
