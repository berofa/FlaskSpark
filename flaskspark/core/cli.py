"""Command line of an application built on flaskspark.core: `flaskspark` (FlaskSpark's console script), or an alias of
the app's own (e.g. `myapp = "flaskspark.core.cli:main"`).

    run                   every service in one process tree (flaskspark.core.supervisor): single container, development
    service <name>        one service of the core or a module (its own process, e.g. in its own container); <name> is
                          the short name ("push") or the process name ("flaskspark-push")
    router                the router alone (the same as `service router`)
    services              the services of this installation: name, process name, systemd unit, label, entry
    routes                the router's routes (for a reverse proxy in front of separate containers)
    modules               the loaded modules (and the installed ones that are not, with the reason) and the theme
    db upgrade            every module's migrations (and the core's) to their heads, with a backup first
    db current            where every history stands
    db check              what differs between the models and the database (exit 1 with a difference)
    db revision -m <msg> --module <name> [--empty]
                          a new revision of a module, autogenerated against its tables only
    db adopt              take over a database of an earlier single history (README «Migrations»)
    data                  what modules no longer delivered left behind (flaskspark.core.leftovers)
    data clean <id…|all> [--yes]
                          remove them, after a backup
    status                the services' status tiles (flaskspark.core.status), exit 1 with a problem
    units                 the systemd units of the services (ServiceInfo.unit, default flaskspark-<name>.service)
    guard-check           the guardian's checks once, with their findings (nothing is sent), exit 1 with one
    backup                one backup run (flaskspark.core.backup): database, state directory, prune
    backup-list           the backups
    backup-check <file>   integrity and rows per table of a database backup, exit 1 when broken
    backup-restore <file> a database backup in place of the live database (stop the services first)
    <command> …           a command of a module (Module.CLI, e.g. `myapp notes import`): the same as
                          `flask --app flaskspark.core.web.app:create_app <command> …`, in the web app's context
"""

from __future__ import annotations

import argparse
import importlib
import json
import sys

from . import config, modules
from .service import PREFIX, process_name


def _entry(entry: str):
    module, _, function = entry.partition(":")
    return getattr(importlib.import_module(module), function or "main")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog=config.load().app_name)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("run", help="all services (supervisor)")
    service = sub.add_parser("service", help="one service")
    service.add_argument("name")
    sub.add_parser("router", help="the router")
    sub.add_parser("services", help="list the services")
    sub.add_parser("routes", help="list the router's routes")
    sub.add_parser("modules", help="list the modules")
    database = sub.add_parser("db", help="migrations")
    db_sub = database.add_subparsers(dest="db_command", required=True)
    db_sub.add_parser("upgrade", help="every history to its head")
    db_sub.add_parser("current", help="where every history stands")
    db_sub.add_parser("check", help="differences between the models and the database")
    db_sub.add_parser("adopt", help="take over a database of an earlier single history")
    rev = db_sub.add_parser("revision", help="a new revision of a module")
    rev.add_argument("-m", "--message", required=True)
    rev.add_argument("--module", required=True)
    rev.add_argument("--empty", action="store_true", help="an empty revision (no autogenerate)")
    data = sub.add_parser("data", help="what modules no longer delivered left behind")
    data_sub = data.add_subparsers(dest="data_command")
    clean = data_sub.add_parser("clean", help="remove leftovers (after a backup)")
    clean.add_argument("items", nargs="+", help="ids as `data` lists them, or all")
    clean.add_argument("--yes", action="store_true", help="do not ask")
    sub.add_parser("status", help="the services' status")
    sub.add_parser("units", help="list the services' systemd units")
    sub.add_parser("guard-check", help="run the guardian's checks once (nothing is sent)")
    sub.add_parser("backup", help="one backup run")
    sub.add_parser("backup-list", help="list the backups")
    check = sub.add_parser("backup-check", help="check a database backup")
    check.add_argument("file")
    restore = sub.add_parser("backup-restore", help="restore a database backup (services stopped)")
    restore.add_argument("file")
    restore.add_argument("--yes", action="store_true", help="do not ask")
    words = list(sys.argv[1:] if argv is None else argv)
    if words and not words[0].startswith("-") and words[0] not in sub.choices:
        commands = module_commands(config.load())
        if words[0] in commands:
            sys.exit(run_module_command(words, parser.prog))
    elif words and words[0] in ("-h", "--help"):
        try:
            names = sorted(module_commands(config.load()))
        except Exception:  # noqa: BLE001 - the help must show
            names = []
        if names:
            parser.epilog = "commands of the modules: " + ", ".join(names) + " (<command> --help)"
    args = parser.parse_args(argv)
    cfg = config.load()

    if args.command == "run":
        from .supervisor import run

        run()
    elif args.command == "service":
        name = args.name.removeprefix(f"{PREFIX}-")
        found = next((s for s in modules.services(cfg) if s.name == name), None)
        if found is None:
            sys.exit(f"no service {args.name!r} (services: {', '.join(s.name for s in modules.services(cfg))})")
        _entry(found.entry)()
    elif args.command == "router":  # the same as `service router`
        from .services.router.service import main as router

        router()
    elif args.command == "services":
        for s in modules.services(cfg):
            print(f"{s.name:<14} {process_name(s.name):<26} {s.unit:<34} {s.label:<24} {s.entry}")
    elif args.command == "routes":
        from .services.router.service import targets

        for t in targets(modules.load(cfg)):
            print(f"{t.prefix:<24} 127.0.0.1:{t.port}{'  (websocket)' if t.websocket else ''}")
    elif args.command == "units":
        for s in modules.services(cfg):
            if s.unit:
                print(s.unit)
    elif args.command == "guard-check":
        sys.exit(_guard_check(cfg))
    elif args.command in ("status", "backup", "backup-list", "backup-check", "backup-restore"):
        sys.exit(_operations(args, cfg))
    elif args.command == "modules":
        print(f"theme: {cfg.theme}")
        for m in modules.load(cfg):
            print(f"{m.NAME:<12} {m.LABEL:<24} {m.PACKAGE or 'flaskspark.core'}")
        for name, why in modules.skipped(cfg).items():
            print(f"{name:<12} not loaded: {why}")
    elif args.command == "db":
        sys.exit(_db(args, cfg))
    elif args.command == "data":
        sys.exit(_data(args, cfg))


def module_commands(cfg) -> dict:
    """The commands the loaded modules add (Module.CLI, click commands or groups): name -> command."""
    out = {}
    for module in modules.load(cfg):
        if module.CLI:
            command = modules.resolve(module.CLI)
            out[command.name] = command
    return out


def run_module_command(words: list[str], prog: str) -> int:
    """A module's command in the built-in web app's context (Flask's CLI, like `flask --app … <command>`)."""
    from flask.cli import FlaskGroup

    from .web.app import create_app

    group = FlaskGroup(name=prog, create_app=create_app, add_default_commands=False, add_version_option=False,
                       load_dotenv=False,
                       set_debug_flag=False)
    try:
        group.main(args=words, prog_name=prog, standalone_mode=True)
    except SystemExit as done:
        return done.code if isinstance(done.code, int) else (0 if done.code is None else 1)
    return 0


def _describe(item: dict) -> str:
    kind = item["kind"]
    if kind == "module":
        tables = ", ".join(f"{t['name']} ({t['rows']} rows)" for t in item["tables"]) or "no tables left"
        revisions = ", ".join(item["revisions"]) or "none"
        return f"no longer delivered, last seen {item['version'] or '?'}: tables {tables}; revision {revisions}"
    if kind == "table":
        return f"table no module describes ({item['rows']} rows)"
    if kind == "revision":
        return "migration revision of no known module"
    if kind == "setting":
        return f"stored setting no module defines: {json.dumps(item['value'], ensure_ascii=False)}"
    if kind == "area":
        return f"access cells of an area that is gone ({item['rows']} rows)"
    if kind == "user-setting":
        return f"personal settings of module {item['module']} ({item['rows']} rows)"
    return f"state directory {item['path']} ({item['size'] // 1024} kB)"


def _data(args, cfg) -> int:
    """What modules no longer delivered left behind, and its clean-up; returns the exit code."""
    from . import leftovers

    found = leftovers.find(cfg)
    if args.data_command != "clean":
        for item in found:
            print(f"{item['id']:<40} {_describe(item)}")
        if not found:
            print("nothing left over")
        return 0
    by_id = {item["id"]: item for item in found}
    chosen = list(by_id) if args.items == ["all"] else args.items
    unknown = [i for i in chosen if i not in by_id]
    if unknown:
        print(f"error: not left over: {', '.join(unknown)} (see `data`)", file=sys.stderr)
        return 1
    if not chosen:
        print("nothing left over")
        return 0
    print("This deletes for good (a backup is made first):")
    for i in chosen:
        print(f"  {i:<40} {_describe(by_id[i])}")
    if not args.yes and input("Remove? [y/N] ").lower() != "y":
        return 1
    try:
        result = leftovers.clean(cfg, chosen)
    except leftovers.LeftoverError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


def _db(args, cfg) -> int:
    """The migrations' commands (flaskspark.core.db.migrations); returns the exit code."""
    import logging

    from .db import migrations

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    logging.getLogger("alembic").setLevel(logging.WARNING)  # the commands print what they did themselves
    if migrations.classic():
        print("This project keeps its migrations in web/migrations (Flask-Migrate): `flask db ...` in web/.",
              file=sys.stderr)
        return 2
    try:
        if args.db_command == "upgrade":
            result = migrations.upgrade(cfg)
            for name, (old, new) in result["applied"].items():
                print(f"{name:<12} {old or 'empty'} -> {new}")
            print(f"backup: {result['backup']}" if result["backup"] else
                  "nothing to do" if not result["applied"] else "no backup (empty database)")
            return 0
        if args.db_command == "current":
            found = migrations.state(cfg)
            for name, head in found.heads.items():
                now = found.current.get(name)
                print(f"{name:<12} {now or '-':<14} {'(head)' if now == head else f'head {head}'}")
            for name, entry in found.vanished.items():
                print(f"{name:<12} {', '.join(entry['revisions']):<14} no longer delivered (tables kept: "
                      f"{', '.join(entry['tables']) or 'none'}; `data` lists the leftovers)")
            for rev in found.foreign:
                print(f"unknown revision {rev} (no module known to have it; left as it is)")
            for name, tables in found.unversioned.items():
                print(f"{name:<12} tables without a revision: {', '.join(tables)} (db adopt)")
            return 0
        if args.db_command == "check":
            found = migrations.differences(cfg)
            for name, diffs in found.items():
                for diff in diffs:
                    print(f"{name:<12} {diff}")
            if not found:
                print("the database matches the models")
            return 1 if found else 0
        if args.db_command == "adopt":
            report = migrations.adopt(cfg)
            print(json.dumps(report, indent=2))
            print("next: db upgrade (the revisions after the stamped ones, the histories marked new)")
            return 0
        if args.db_command == "revision":
            files = migrations.revision(cfg, args.module, args.message, autogenerate=not args.empty)
            for path in files:
                print(path)
            if not files:
                print("no changes: no revision written")
            return 0
    except migrations.MigrationError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 2


def _guard_check(cfg) -> int:
    """The guardian's checks once: every finding (with its grace time), exit 1 with one."""
    from .services.guardian import GuardContext, default_checks, findings, settings

    checks = default_checks(cfg)
    found = findings(cfg, checks, GuardContext(cfg, settings(cfg, checks)))
    for f in found:
        title, message = f.render(cfg=cfg)  # the source texts with their values, in the application's language
        print(f"[{f.level}] {title}: {message}" + (f" (reported after {f.grace:.0f} s)" if f.grace else ""))
    print(f"{len(found)} finding(s).")
    return 1 if found else 0


def _operations(args, cfg) -> int:
    """The commands of the status and the backup; returns the exit code."""
    from pathlib import Path

    from . import backup

    if args.command == "status":
        from . import status

        tiles = status.collect(cfg)
        for t in tiles:
            print(f"{t['level']:<8} {t['name']:<20} {t.get('process') or '':<26} {t['summary']}")
            for row in t["details"]:
                print(f"{'':<9}{row[0]}: {row[-1]}")
        return 1 if any(t["level"] == status.ERROR for t in tiles) else 0
    if args.command == "backup":
        print(json.dumps(backup.run(cfg), indent=2))
        return 0
    if args.command == "backup-list":
        for kind, _, path in backup.backups(backup.settings(cfg)["dir"]):
            print(f"{kind:<6} {path.stat().st_size // 1024:>8} kB  {path}")
        return 0
    if args.command == "backup-check":
        result = backup.verify(Path(args.file))
        print(json.dumps(result, indent=2))
        return 0 if result["integrity"] == "ok" else 1
    from . import db

    if not args.yes and input(f"Replace the database {db.location()} with {args.file}? [y/N] ").lower() != "y":
        return 1
    print(json.dumps(backup.restore(Path(args.file)), indent=2))
    return 0


if __name__ == "__main__":
    main()
